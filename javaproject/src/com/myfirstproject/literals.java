package com.myfirstproject;

public class literals {
	public static void main(String[]args){
		int age=22;
		float price=200.99f;
		char grade='A';
		String name="Radhika";
		boolean isstudent=true;
		System.out.println("integer literal:"+age);
		System.out.println("floating literal:"+price);
		System.out.println("character literal:"+grade);
		System.out.println("String literal:"+name);
		System.out.println("boolean literal:"+ isstudent);
	}
}

		
		
	
